① 本研究の内容及び目的
本研究は，東京の下町における新たな地域資源の発見と創出のプロセスを，まち歩きを通じた観察調査により明らかにするものです．まち歩きで収集したデータをGIS（地理情報システム）上で可視化して分析することを目的とします．

